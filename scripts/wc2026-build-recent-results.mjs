// One-time generator: builds apps/backend/src/wc2026/recent-results.data.ts — a
// static snapshot of the last ~12 months of international matches that involve
// at least one WC 2026 nation, with final scores and a competition category.
//
// Why: strength.ts rates teams from ACTUAL results, and the dominant signal we
// want is recent form (this snapshot) plus the tournament so far. The FIFA
// ranking is only a light anchor. ESPN exposes finished national-team matches
// with scores for free, but split across competition codes (friendlies,
// confederation qualifiers, Nations Leagues, continental cups) — so we sweep
// each one's scoreboard over the window and keep the matches that touch a WC
// nation. Opponents that aren't WC teams stay in the data (seeded at the neutral
// base in strength.ts) so the Elo has a real opponent on both sides.
//
// Run from the repo root (no key — ESPN is public):
//   node scripts/wc2026-build-recent-results.mjs

import { writeFileSync } from 'node:fs';

const UA = 'Mozilla/5.0 (CromoWC2026; recent-results)';
const OUT = 'apps/backend/src/wc2026/recent-results.data.ts';
const SITE = 'https://site.api.espn.com/apis/site/v2/sports/soccer';

// competition code → category (strength.ts maps category → Elo importance K).
const LEAGUES = {
  'fifa.friendly': 'friendly',
  'uefa.nations': 'nations',
  'concacaf.nations.league': 'nations',
  'fifa.worldq.uefa': 'qualifier',
  'fifa.worldq.conmebol': 'qualifier',
  'fifa.worldq.concacaf': 'qualifier',
  'fifa.worldq.afc': 'qualifier',
  'fifa.worldq.caf': 'qualifier',
  'fifa.worldq.ofc': 'qualifier',
  'concacaf.gold': 'continental',
  'caf.nations': 'continental',
  'afc.asian': 'continental',
  'conmebol.america': 'continental',
  'uefa.euro': 'continental',
};

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function getJson(url, attempt = 0) {
  try {
    const r = await fetch(url, { headers: { 'User-Agent': UA }, signal: AbortSignal.timeout(20000) });
    if (r.status === 429 || r.status >= 500) throw new Error(`espn ${r.status}`);
    if (!r.ok) return null;
    return await r.json();
  } catch (e) {
    if (attempt < 3) {
      await sleep(1500 * (attempt + 1));
      return getJson(url, attempt + 1);
    }
    return null;
  }
}

const ymd = (d) => d.toISOString().slice(0, 10).replace(/-/g, '');

// 3-month windows covering ~13 months back from today (we filter to 12 in code).
function dateChunks() {
  const chunks = [];
  const end = new Date();
  const start = new Date(end);
  start.setMonth(start.getMonth() - 13);
  let cur = new Date(start);
  while (cur < end) {
    const next = new Date(cur);
    next.setMonth(next.getMonth() + 3);
    chunks.push(`${ymd(cur)}-${ymd(next < end ? next : end)}`);
    cur = next;
  }
  return chunks;
}

async function main() {
  console.log('Fetching the 48 WC nations…');
  const teamsDoc = await getJson(`${SITE}/fifa.world/teams`);
  const wc = new Set(
    (teamsDoc?.sports?.[0]?.leagues?.[0]?.teams ?? []).map((t) => (t.team ?? t).abbreviation).filter(Boolean),
  );
  if (wc.size === 0) throw new Error('no WC nations from ESPN');
  console.log(`  ${wc.size} nations`);

  const cutoff = new Date();
  cutoff.setFullYear(cutoff.getFullYear() - 1);
  const chunks = dateChunks();
  const byId = new Map(); // event id → match (dedupe across chunks)

  for (const [code, cat] of Object.entries(LEAGUES)) {
    let kept = 0;
    for (const range of chunks) {
      const doc = await getJson(`${SITE}/${code}/scoreboard?dates=${range}`);
      for (const ev of doc?.events ?? []) {
        if (byId.has(ev.id)) continue;
        const comp = ev.competitions?.[0];
        const cs = comp?.competitors ?? [];
        const home = cs.find((c) => c.homeAway === 'home');
        const away = cs.find((c) => c.homeAway === 'away');
        const h = home?.team?.abbreviation;
        const a = away?.team?.abbreviation;
        const finished = comp?.status?.type?.state === 'post' || comp?.status?.type?.completed;
        const hs = Number(home?.score);
        const as = Number(away?.score);
        if (!h || !a || !finished || Number.isNaN(hs) || Number.isNaN(as)) continue;
        if (!wc.has(h) && !wc.has(a)) continue; // must touch a WC nation
        if (new Date(ev.date) < cutoff) continue;
        byId.set(ev.id, { d: ev.date.slice(0, 10), h, a, hs, as, k: cat });
        kept += 1;
      }
      await sleep(120);
    }
    console.log(`  ${code}: ${kept} matches`);
  }

  const rows = [...byId.values()].sort((x, y) => (x.d < y.d ? -1 : x.d > y.d ? 1 : 0));
  const header =
    '// GENERATED by scripts/wc2026-build-recent-results.mjs — do not edit by hand.\n' +
    '// Last ~12 months of international matches involving a WC 2026 nation (ESPN),\n' +
    '// the dominant input to strength.ts. { d: date, h/a: FIFA codes, hs/as: score,\n' +
    "// k: competition category }. Regenerate to refresh recent form.\n";
  writeFileSync(
    OUT,
    header +
      "export type RecentCategory = 'friendly' | 'nations' | 'qualifier' | 'continental';\n" +
      'export interface RecentMatch { d: string; h: string; a: string; hs: number; as: number; k: RecentCategory }\n' +
      'export const RECENT_RESULTS: RecentMatch[] = ' +
      JSON.stringify(rows, null, 0) +
      ';\n',
  );
  console.log(`\nDone. ${rows.length} matches → ${OUT}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
