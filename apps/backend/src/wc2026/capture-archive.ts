// One-shot CLI: freeze a FINISHED tournament into a committed static archive.
//
// A finished tournament's results never change, so instead of polling the live
// provider forever (whose competition code eventually rolls over to the next
// edition), we capture the real normalized data ONCE into a `.ts` data module
// under ./archive/. The registry then serves that file for a
// `status: 'complete'` tournament — no network, immune to cache flushes and to
// the upstream `WC` code rolling to the next World Cup.
//
// Mirrors the existing static-snapshot builders (scripts/wc2026-build-*.mjs):
// real provider data only, never fabricated. Run inside the api container,
// which holds the live WC_API_KEY:
//
//   docker compose -f infrastructure/docker/docker-compose.yml \
//     exec -w /app/apps/backend api pnpm exec tsx src/wc2026/capture-archive.ts wc-2026 WC
//
// Args: <slug> [competitionCode=WC]. Writes src/wc2026/archive/<slug>.data.ts.

import { mkdirSync, writeFileSync } from 'node:fs';
import { env } from '../env.js';
import { fetchLiveMatches, fetchLiveSquads } from './live-provider.js';
import { fetchEspnKnockout } from './espn-knockout-provider.js';
import type { RawMatch } from './types.js';

const slug = process.argv[2];
const competition = process.argv[3] ?? 'WC';
if (!slug) {
  console.error('usage: tsx src/wc2026/capture-archive.ts <slug> [competitionCode=WC]');
  process.exit(1);
}
if (env.WC_API_KEY === 'mock') {
  console.error('WC_API_KEY is "mock" — set a real football-data key to capture live data.');
  process.exit(1);
}

// Assemble exactly what the live path in wc2026.service.ts produces: group
// fixtures/standings/squads from football-data, knockout from ESPN (the
// official bracket), with the same degradation rules.
const matchData = await fetchLiveMatches(env.WC_API_KEY, competition);
const [squads, espnKnockout] = await Promise.all([
  fetchLiveSquads(env.WC_API_KEY, competition).catch(() => ({})),
  fetchEspnKnockout().catch(() => [] as RawMatch[]),
]);
const groupMatches = matchData.matches.filter((m) => m.stage === 'GROUP');
const knockout = espnKnockout.length ? espnKnockout : matchData.matches.filter((m) => m.stage !== 'GROUP');
const archive = { matches: [...groupMatches, ...knockout], teams: matchData.teams, squads };

const final = archive.matches.find((m) => m.stage === 'FINAL');
console.log(
  `[capture] ${slug}: ${archive.matches.length} matches, ${archive.teams.length} teams, ${Object.keys(squads).length} squads`,
);
console.log(
  `[capture] FINAL: ${final?.homeCode ?? '?'} ${final?.homeScore ?? '-'}–${final?.awayScore ?? '-'} ${final?.awayCode ?? '?'} (${final?.status ?? 'n/a'})`,
);

const CONST = `${slug.replace(/[^a-z0-9]+/gi, '_').toUpperCase()}_ARCHIVE`;
const body = `// AUTO-GENERATED by src/wc2026/capture-archive.ts — DO NOT edit by hand.
// Frozen snapshot of a finished tournament (real football-data + ESPN data),
// captured ${new Date().toISOString()}. Regenerate with the capture CLI.
import type { RawMatch, TeamMeta, WcPlayer } from '../types.js';

export const ${CONST}: { matches: RawMatch[]; teams: TeamMeta[]; squads: Record<string, WcPlayer[]> } =
${JSON.stringify(archive, null, 2)};
`;

mkdirSync('src/wc2026/archive', { recursive: true });
const out = `src/wc2026/archive/${slug}.data.ts`;
writeFileSync(out, body);
console.log(`[capture] wrote ${out} (export ${CONST})`);
